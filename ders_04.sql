SELECT
    DEPARTMENT_ID,
    ROUND(AVG(SALARY)) AS ORTA_MAAS
FROM
    HR.EMPLOYEES
GROUP BY
    DEPARTMENT_ID
HAVING
    AVG(SALARY) > (
        SELECT
            AVG(SALARY)
        FROM
            HR.EMPLOYEES
        WHERE
            DEPARTMENT_ID = (
                SELECT
                    DEPARTMENT_ID
                FROM
                    HR.DEPARTMENTS
                WHERE
                    DEPARTMENT_NAME = 'IT'
            )
    )
ORDER BY
    ORTA_MAAS DESC;
