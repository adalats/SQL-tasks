-- Task 1
SELECT JOB_TITLE, MAX_SALARY
FROM HR.JOBS
WHERE MAX_SALARY > (
    SELECT AVG(MAX_SALARY)
    FROM HR.JOBS
)
ORDER BY MAX_SALARY DESC;
-- Task 2
SELECT FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = (
    SELECT DEPARTMENT_ID
    FROM HR.EMPLOYEES
    WHERE FIRST_NAME = 'Steven'
      AND LAST_NAME = 'King'
)
AND NOT (
    FIRST_NAME = 'Steven'
    AND LAST_NAME = 'King'
);
-- Task 3
SELECT FIRST_NAME, LAST_NAME, JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID IN (
    SELECT JOB_ID
    FROM HR.EMPLOYEES
    GROUP BY JOB_ID
    HAVING COUNT(*) = 1
)
ORDER BY JOB_ID;
-- Task 4
SELECT DEPARTMENT_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) > (
    SELECT COUNT(*)
    FROM HR.EMPLOYEES
    WHERE DEPARTMENT_ID = (
        SELECT DEPARTMENT_ID
        FROM HR.DEPARTMENTS
        WHERE DEPARTMENT_NAME = 'IT'
    )
)
ORDER BY ISCI_SAYI DESC;
-- Task 5
SELECT FIRST_NAME, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (
    SELECT DEPARTMENT_ID
    FROM HR.DEPARTMENTS
    WHERE LOCATION_ID IN (
        SELECT LOCATION_ID
        FROM HR.LOCATIONS
        WHERE COUNTRY_ID IN (
            SELECT COUNTRY_ID
            FROM HR.COUNTRIES
            WHERE COUNTRY_NAME = 'United Kingdom'
        )
    )
);
-- Task 6
SELECT JOB_TITLE, MIN_SALARY, MAX_SALARY
FROM HR.JOBS
WHERE JOB_ID IN (
    SELECT JOB_ID
    FROM HR.EMPLOYEES
    GROUP BY JOB_ID
    HAVING COUNT(*) = (
        SELECT MAX(ISCI_SAYI)
        FROM (
            SELECT COUNT(*) AS ISCI_SAYI
            FROM HR.EMPLOYEES
            GROUP BY JOB_ID
        )
    )
);