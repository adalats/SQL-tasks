SELECT M.FIRST_NAME AS MENECER_ADI, M.LAST_NAME AS MENECER_SOYADI, COUNT(E.EMPLOYEE_ID) AS TABE_SAYI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M 
ON E.MANAGER_ID = M.EMPLOYEE_ID 
GROUP BY M.FIRST_NAME, M.LAST_NAME 
ORDER BY COUNT(E.EMPLOYEE_ID) DESC;

