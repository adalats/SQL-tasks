-- TASK 1
SELECT
    FIRST_NAME,
    SALARY,
    CASE 
     WHEN SALARY < 3000 THEN 'Cox asagi'
     WHEN SALARY < 7000 THEN 'Asagi'
     WHEN SALARY < 12000 THEN 'Orta'
     ELSE 'Yuksek'
    END AS KATEQORIYA
FROM HR.EMPLOYEES;

-- TASK 2
SELECT FIRST_NAME, DEPARTMENT_ID,
    CASE DEPARTMENT_ID 
        WHEN 10 THEN 'Admin'
        WHEN 20 THEN 'Marketing'
        WHEN 60 THEN 'IT'
        WHEN 90 THEN 'Rehberlik'
        ELSE 'Diger'
    END SOBE_ADI
FROM HR.EMPLOYEES;

--TASK 3
SELECT FIRST_NAME, NVL(MANAGER_ID, 0) AS MANAGER_ID , NVL(COMMISSION_PCT, 0) AS KOMISSIYA
FROM HR.EMPLOYEES;

--TASK 4
SELECT JOB_TITLE, MAX_SALARY, MIN_SALARY,
CASE WHEN MAX_SALARY - MIN_SALARY < 5000 THEN 'Dar'
WHEN MAX_SALARY - MIN_SALARY < 10000 THEN 'Orta'
WHEN MAX_SALARY - MIN_SALARY > 10000 THEN 'Genis'
END AS ARALIQ
FROM HR.JOBS;

--TASK 5
SELECT FIRST_NAME, SALARY,
NVL(COMMISSION_PCT, 0)*SALARY + SALARY AS AYLIQ_GELIR,
CASE WHEN COMMISSION_PCT IS NOT NULL THEN 'Satici'
ELSE 'Diger'
END AS NOV
FROM HR.EMPLOYEES;

-- TASK 6
SELECT FIRST_NAME, SALARY,
       CASE 
           WHEN COMMISSION_PCT IS NULL THEN 'Komissiyasiz'
           ELSE 'Komissiyali'
       END AS Komissiya
FROM HR.EMPLOYEES;

-- WHEN NULL OLMUR'
-- Komissiyali
-- END AS DIRNAQ YOX

--TASK 7
SELECT FIRST_NAME, JOB_ID, SALARY,
CASE WHEN JOB_ID LIKE 'AD%' THEN 'Rehberlik'
WHEN (JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR') AND SALARY > 12000 THEN 'Boyuk menecer'
WHEN JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR' THEN 'Menecer'
ELSE 'Isci'
END AS ROL
FROM HR.EMPLOYEES;

--TASK 8
SELECT FIRST_NAME, SALARY, COMMISSION_PCT,
CASE WHEN NVL(COMMISSION_PCT, 0) >= 0.3 THEN 'Yuksek'
WHEN NVL(COMMISSION_PCT, 0) >= 0.2 THEN 'Yuksek'
ELSE 'Asagi'
END AS KOMISSIYA_SEVIYYESI
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80
ORDER BY KOMISSIYA_SEVIYYESI DESC, SALARY DESC;

--TASK 9
SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
CASE WHEN DEPARTMENT_ID = 80 THEN SALARY + SALARY*NVL(COMMISSION_PCT, 0)
WHEN DEPARTMENT_ID = 50 AND SALARY < 1500 THEN 1.15 * SALARY
WHEN DEPARTMENT_ID = 50 THEN 1.05 * SALARY
WHEN DEPARTMENT_ID IS NULL THEN SALARY
ELSE SALARY * 1.03
END AS YENI_MAAS
FROM HR.EMPLOYEES
ORDER BY YENI_MAAS DESC; 

--TASK 10
SELECT FIRST_NAME, SALARY, NVL(COMMISSION_PCT, 0), 12*SALARY + SALARY*12*NVL(COMMISSION_PCT, 0) AS ILLIK_MAAS,
CASE WHEN 12*SALARY + SALARY*12*NVL(COMMISSION_PCT, 0) < 50000 THEN 'Asagi'
WHEN 12*SALARY + SALARY*12*NVL(COMMISSION_PCT, 0) < 150000 THEN 'Orts'
ELSE 'Yuksek'
END AS GELIR_SEVIYYESI
FROM HR.EMPLOYEES
ORDER BY ILLIK_MAAS DESC;