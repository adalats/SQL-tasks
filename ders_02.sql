--TASK 9
SELECT D.DEPARTMENT_NAME, J.JOB_TITLE, COUNT(*) AS ISCI_SAYI, CEIL(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID
GROUP BY D.DEPARTMENT_NAME, J.JOB_TITLE
HAVING COUNT(*) >= 3
ORDER BY D.DEPARTMENT_NAME ASC, COUNT(*) DESC; 

--TASK 10
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, COUNT(J.EMPLOYEE_ID) AS KECMIS_VEZIFE_SAYI
FROM HR.EMPLOYEES E 
LEFT JOIN HR.JOB_HISTORY J 
ON E.EMPLOYEE_ID = J.EMPLOYEE_ID 
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME
ORDER BY COUNT(J.EMPLOYEE_ID) DESC;
