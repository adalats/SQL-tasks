-- TASK 1
SELECT JOB_ID, COUNT(*) AS ISCI_SAYI, FLOOR(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY JOB_ID
ORDER BY COUNT(*) DESC;

--TASK 2
SELECT DEPARTMENT_ID, MIN(SALARY) AS MIN_MAAS , MAX(SALARY) AS MAX_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID;

--TASK 3
SELECT D.DEPARTMENT_NAME, L.CITY
FROM HR.DEPARTMENTS D
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID;

--TASK 4
SELECT JOB_ID, SUM(SALARY) AS MAAS_CEMI
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING SUM(SALARY) > 50000
ORDER BY SUM(SALARY) DESC;

--TASK 5
SELECT MANAGER_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL
GROUP BY MANAGER_ID
HAVING COUNT(*) > 5;

--TASK 6
SELECT CITY, COUNT(*) AS SOBE_SAYI
FROM HR.DEPARTMENTS D
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY CITY
ORDER BY SOBE_SAYI DESC;

--TASK 7
SELECT FIRST_NAME, LAST_NAME, DEPARTMENT_NAME
FROM HR.EMPLOYEES E
FULL JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID 
WHERE E.EMPLOYEE_ID IS NULL OR D.DEPARTMENT_ID IS NULL;

--TASK 8
SELECT D.DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(*) > 3;

