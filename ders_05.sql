--TASK 1
SELECT
    CONCAT(FIRST_NAME,
           ' ',
           UPPER(LAST_NAME)) AS TAM_AD,
    CONCAT(
        SUBSTR(FIRST_NAME, 1, 1),
        '.',
        LAST_NAME
    )                        AS QISA_AD,
    LOWER(CONCAT(
        SUBSTR(FIRST_NAME, 1, 1),
        LAST_NAME,
        '@company.com'
    ))                       AS EMAIL
FROM
    HR.EMPLOYEES
ORDER BY
    LAST_NAME;

--TASK 2
SELECT
    FIRST_NAME,
    CONCUT(
        TO_CHAR(SALARY, 'FM999,999'),
        'AZN'
    )                                    AS MAAS,
    TO_CHAR(SALARY * 12, 'FM999,999.00') AS ILLIK_MAAS
FROM
    HR.EMPLOYEES
ORDER BY
    SALARY DESC;
-- MAAS CHARA GORE SIRALAYIR

--TASK 3
SELECT
    FIRST_NAME,
    TO_CHAR(HIRE_DATE, 'DD.MM.YYYY') AS ISE_GIRIS,
    EXTRACT(YEAR FROM HIRE_DATE)     AS IL,
    TO_CHAR(HIRE_DATE, 'FMMonth')    AS AY_ADI,
    TO_CHAR(HIRE_DATE, 'FMDay')      AS HEFTE_GUNU
FROM
    HR.EMPLOYEES
ORDER BY
    HIRE_DATE;

--TASK 4
SELECT
    CONCAT(FIRST_NAME, ' ', LAST_NAME)                     AS ISCI,
    TO_CHAR(HIRE_DATE, 'FMDD Month YYYY')                  AS ISE_GIRIS,
    TRUNC(MONTHS_BETWEEN(SYSDATE, HIRE_DATE) / 12)
    || MOD(TRUNC(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)) , 12) AS STAJ
FROM
    HR.EMPLOYEES
    ORDER BY MONTHS_BETWEEN(SYSDATE, HIRE_DATE);

--TASK 5
--A
SELECT FIRST_NAME, HIRE_DATE, ADD_MONTHS(HIRE_DATE, 3) AS SINAQ_BITIR, LAST_DAY(ADD_MONTHS(HIRE_DATE, 3)) AS ILK_MAAS_GUNU,  LAST_DAY(ADD_MONTHS(HIRE_DATE, 3))-ADD_MONTHS(HIRE_DATE, 3) AS MAASA_QALAN_GUN
FROM HR.EMPLOYEES;

--B
SELECT ADD_MONTHS(TO_DATE('28.02.2025', 'DD.MM.YYYY'), 3) FROM DUAL;
