--TASK 6
SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) || ', komissiya: ' || NVL(TO_CHAR(COMMISSION_PCT, '0.00'),'yoxdur' ) AS MELUMAT
FROM HR.EMPLOYEES
WHERE TO_CHAR(HIRE_DATE, 'MM') = '03';
--NVL EYNI TIP
-- MM 03
--0.00


--TASK 7
SELECT TO_CHAR(HIRE_DATE, 'MM') AS AY_NO, TO_CHAR(HIRE_DATE, 'FMMonth') AS AY, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY TO_CHAR(HIRE_DATE, 'MM'), TO_CHAR(HIRE_DATE, 'FMMonth')
ORDER BY AY_NO;
